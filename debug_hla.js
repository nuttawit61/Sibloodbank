// Premium Web Audio API synthesized click-click sound effect
function playClickSound() {
  try {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (!AudioContext) return;
    const ctx = new AudioContext();
    const osc1 = ctx.createOscillator();
    const gain1 = ctx.createGain();
    osc1.connect(gain1);
    gain1.connect(ctx.destination);
    osc1.type = 'triangle';
    osc1.frequency.setValueAtTime(2500, ctx.currentTime);
    osc1.frequency.exponentialRampToValueAtTime(800, ctx.currentTime + 0.012);
    gain1.gain.setValueAtTime(0.04, ctx.currentTime);
    gain1.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 0.012);
    osc1.start();
    osc1.stop(ctx.currentTime + 0.012);
    
    const osc2 = ctx.createOscillator();
    const gain2 = ctx.createGain();
    osc2.connect(gain2);
    gain2.connect(ctx.destination);
    osc2.type = 'triangle';
    osc2.frequency.setValueAtTime(2000, ctx.currentTime + 0.03);
    osc2.frequency.exponentialRampToValueAtTime(600, ctx.currentTime + 0.042);
    gain2.gain.setValueAtTime(0.02, ctx.currentTime + 0.03);
    gain2.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + 0.042);
    osc2.start(ctx.currentTime + 0.03);
    osc2.stop(ctx.currentTime + 0.042);
  } catch (e) {
    console.warn("Click sound failed:", e);
  }
}

