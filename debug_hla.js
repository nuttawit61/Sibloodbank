function getAvailableIdxs() {
  const d = HLA_YEARS[selectedYear];
  if (!d) return [];
  let available = [];
  for (let i = 0; i < 12; i++) {
    let hasVal = false;
    for (let k in d) {
      if (d[k] && d[k][i] !== null) { hasVal = true; break; }
    }
    if (hasVal) available.push(i);
  }
  return available;
}

function hasData(idx) { return getAvailableIdxs().includes(idx); }

function sumOf(key, indices) {
  const d = HLA_YEARS[selectedYear];
  if (!d || !d[key]) return 0;
  return indices.reduce((acc, i) => acc + (parseFloat(d[key][i]) || 0), 0);
}

function fmt(num) { return num.toLocaleString('en-US'); }
function pct(part, total) { return total > 0 ? ((part / total) * 100).toFixed(1) : '0.0'; }

function delta(curr, prev) {
  if (prev === 0) return curr > 0 ? 100 : 0;
  return ((curr - prev) / prev) * 100;
}

function d2badge(d, prevY) {
  if (isNaN(d)) return '';
  if (d > 0) return `<span class="badge badge-danger">โ–ฒ +` + d.toFixed(1) + `% YoY (vs ${prevY})</span>`;
  if (d < 0) return `<span class="badge badge-success">โ–ผ ` + d.toFixed(1) + `% YoY (vs ${prevY})</span>`;
  return `<span class="badge badge-secondary">- 0% YoY</span>`;
}

